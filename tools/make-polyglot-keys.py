"""Writes src/libs/book/polyglotkeys.inc from Fruit's random.cpp (the PolyGlot keys)."""
import os
import re

here = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
src = open(os.path.join(here, 'engines', 'fruit', 'src', 'random.cpp')).read()
vals = re.findall(r'U64\((0x[0-9A-Fa-f]+)\)', src)
assert len(vals) == 781, len(vals)
out = ['// SPDX-License-Identifier: GPL-2.0-or-later',
       '// The 781 random numbers of the PolyGlot opening book format (Fabien Letouzey),',
       '// taken from Fruit 2.1 (engines/fruit/src/random.cpp, GPL-2.0-or-later).',
       '// Generated by tools/make-polyglot-keys.py - do not edit.']
for i in range(0, 781, 4):
    out.append('    ' + ', '.join(f'Q_UINT64_C({v})' for v in vals[i:i + 4]) + ',')
with open(os.path.join(here, 'src', 'libs', 'book', 'polyglotkeys.inc'), 'w') as f:
    f.write('\n'.join(out) + '\n')
